def _escape(value: Any) -> str:
    """Escape a value for safe HTML output."""
    if value is None:
        text = ""
    elif isinstance(value, bool):
        text = "Tak" if value else "Nie"
    elif isinstance(value, (dict, list)):
        text = json.dumps(value, ensure_ascii=False, sort_keys=True)
    else:
        text = str(value)
    return html.escape(text, quote=True)


def _display(value: Any, default: str = "n/d") -> str:
    """Escaped display value with a fallback."""
    if value is None or value == "":
        return _escape(default)
    return _escape(value)


def _mapping(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _sequence(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def _number(value: Any) -> float | None:
    """Finite number as float, else None."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    result = float(value)
    return result if math.isfinite(result) else None


def _format_number(value: Any, decimals: int = 3) -> str:
    number = _number(value)
    return "n/d" if number is None else f"{number:.{decimals}f}"


def _format_integer(value: Any) -> str:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        return "n/d"
    return str(value)


def _section(title: str, content: str, section_id: str = "") -> str:
    identifier = f' id="{_escape(section_id)}"' if section_id else ""
    return f"<section{identifier}><h2>{_escape(title)}</h2>{content}</section>"


def _table(headers: list[str], rows: list[list[str]], *, empty_message: str | None = None,
           table_class: str = "") -> str:
    """Responsive table from PRE-ESCAPED cell markup."""
    class_attr = f' class="{_escape(table_class)}"' if table_class else ""
    head = "".join(f'<th scope="col">{_escape(h)}</th>' for h in headers)
    if rows:
        body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    else:
        body = (f'<tr><td colspan="{len(headers)}" class="empty">'
                f"{_escape(empty_message or 'Brak danych')}</td></tr>")
    return (f'<div class="table-wrap"><table{class_attr}><thead><tr>{head}</tr></thead>'
            f"<tbody>{body}</tbody></table></div>")


def _key_value_table(values: Any) -> str:
    rows = [[_escape(k), _escape(v)] for k, v in _mapping(values).items()]
    return _table(["Parametr", "Wartość"], rows, empty_message="Brak danych")


def _matrix_data(value: Any) -> list[list[float]] | None:
    """Finite numeric 4x4 matrix or None."""
    if not isinstance(value, list) or len(value) != 4:
        return None
    matrix: list[list[float]] = []
    for row in value:
        if not isinstance(row, list) or len(row) != 4:
            return None
        conv = [_number(x) for x in row]
        if any(x is None for x in conv):
            return None
        matrix.append(conv)  # type: ignore[arg-type]
    return matrix


def _matrix_html(label: str, value: Any) -> str:
    matrix = _matrix_data(value)
    content = f"<h3>{_escape(label)}</h3>"
    if matrix is None:
        return (f'<div class="matrix-card">{content}<p class="muted">Pozycja X, Y, Z: n/d</p>'
                '<p class="muted">Macierz: n/d</p></div>')
    x, y, z = (_format_number(matrix[i][3]) for i in range(3))
    content += f'<p class="position">X: {x} &nbsp; Y: {y} &nbsp; Z: {z}</p>'
    rows = [[f'<span class="mono">{_escape(_format_number(n))}</span>' for n in row] for row in matrix]
    content += _table(["Kol. 1", "Kol. 2", "Kol. 3", "Kol. 4"], rows, table_class="matrix-table")
    return f'<div class="matrix-card">{content}</div>'


def _joints_html(value: Any) -> str:
    joints = _sequence(value)
    if not joints:
        return '<p class="muted">Pozycja początkowa osi: n/d</p>'
    rendered = ", ".join(_escape(_format_number(j)) for j in joints)
    return f'<p><strong>Pozycja początkowa osi:</strong></p><p class="mono">[{rendered}]</p>'


_SEVERITY_LABEL = {"error": "Błąd", "warning": "Ostrzeżenie", "info": "Informacja"}
_PRIORITY = {"error": 0, "warning": 1, "info": 2}


def _issue_severity(issue: dict[str, Any]) -> str:
    sev = issue.get("severity")
    sev = sev.lower() if isinstance(sev, str) else "info"
    return sev if sev in _PRIORITY else "info"


def _issues_html(validation: dict[str, Any]) -> str:
    """Issues sorted error > warning > info; stable inside a group."""
    issues = [i for i in _sequence(validation.get("issues")) if isinstance(i, dict)]
    ordered = sorted(issues, key=lambda i: _PRIORITY[_issue_severity(i)])
    rows = []
    for it in ordered:
        sev = _issue_severity(it)
        rows.append([f'<span class="severity severity-{sev}">{_SEVERITY_LABEL[sev]}</span>',
                     _display(it.get("code")), _display(it.get("stage")), _display(it.get("instruction")),
                     _display(it.get("source_line")), _display(it.get("message")), _display(it.get("hint"))])
    return _table(["Poziom", "Kod", "Etap", "Instrukcja", "Linia NC", "Komunikat", "Podpowiedź"], rows,
                  empty_message="Brak uwag", table_class="issues-table")


def _outputs_html(value: Any) -> str:
    rows = []
    for out in _sequence(value):
        item = _mapping(out)
        digest = item.get("sha256")
        cell = f'<span class="mono hash">{_display(digest)}</span>' if digest else _display(None)
        rows.append([_display(item.get("file")), cell])
    return _table(["Plik", "SHA-256"], rows, empty_message="Brak plików wyjściowych", table_class="outputs-table")


def _count(validation: dict[str, Any], key: str) -> str:
    value = validation.get(key)
    if isinstance(value, int) and not isinstance(value, bool) and value >= 0:
        return str(value)
    sev = "error" if key == "errors" else "warning"
    return str(sum(1 for i in _sequence(validation.get("issues"))
                   if isinstance(i, dict) and _issue_severity(i) == sev))


def _summary_rows(manifest: dict[str, Any]) -> list[list[str]]:
    inp = _mapping(manifest.get("input"))
    robot = _mapping(_mapping(manifest.get("cell")).get("robot"))
    post = _mapping(manifest.get("post"))
    val = _mapping(manifest.get("validation"))
    ct = _number(val.get("cycle_time_s"))
    commit = manifest.get("git_commit")
    if isinstance(commit, str) and commit:
        commit = commit[:10]
    return [
        ["Plik wejściowy", _display(inp.get("name"))],
        ["Jednostki", _display(inp.get("units"))],
        ["Robot", _display(robot.get("name"))],
        ["Post-procesor", f"{_display(post.get('name'))} / {_display(post.get('version'))}"],
        ["Czas cyklu", _escape(f"{ct:.1f} s" if ct is not None else "n/d")],
        ["Sprawdzone próbki", _escape(_format_integer(val.get("samples_checked")))],
        ["Błędy / ostrzeżenia", _escape(f"{_count(val, 'errors')} / {_count(val, 'warnings')}")],
        ["Utworzono (UTC)", _display(manifest.get("created_utc"))],
        ["Commit Git", _display(commit)],
    ]


