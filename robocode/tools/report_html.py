def write_report(manifest_path: str | Path, out_path: str | Path | None = None) -> Path:
    """Read a JSON manifest and write its HTML report (UTF-8, atomic)."""
    src = Path(manifest_path)
    dst = Path(out_path) if out_path is not None else src.with_suffix(".html")
    with src.open("r", encoding="utf-8-sig") as f:
        manifest = json.load(f)
    return atomic_write_text(dst, render_manifest_html(manifest if isinstance(manifest, dict) else {}))


def main(argv: list[str] | None = None) -> int:
    """CLI: python -m robocode.tools.report_html manifest.json [out.html]"""
    ap = argparse.ArgumentParser(description="Raport HTML z manifestu roboCODE.")
    ap.add_argument("manifest", help="ścieżka do <nazwa>.manifest.json")
    ap.add_argument("out", nargs="?", help="plik HTML (domyślnie obok manifestu)")
    a = ap.parse_args(argv)
    src = Path(a.manifest)
    if not src.is_file():
        print(f"Błąd: plik manifestu nie istnieje: {src}", file=sys.stderr)
        return 1
    try:
        dst = write_report(src, a.out)
    except json.JSONDecodeError as e:
        print(f"Błąd: niepoprawny JSON w {src} (wiersz {e.lineno}, kolumna {e.colno})", file=sys.stderr)
        return 1
    except (OSError, UnicodeError) as e:
        print(f"Błąd odczytu/zapisu: {e}", file=sys.stderr)
        return 1
    print(f"Raport zapisano: {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
