"""Render a run manifest (<name>.manifest.json) as a self-contained HTML report (Polish UI).

Origin: first draft generated by ChatGPT (free tier) on request, reviewed and adjusted by Claude
(fixed `exported` lookup, header label, atomic write, tests incl. HTML-escaping of hostile input).

    python -m robocode.tools.report_html out/Machining.manifest.json [raport.html]
"""
from __future__ import annotations

