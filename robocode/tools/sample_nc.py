"""Generator of example G-code programs (only the dialect from docs/SPECYFIKACJA.md §6.4).

Origin: first draft generated by Gemini (free tier) on request, reviewed and adjusted by Claude
(nested comment parentheses and zero-length moves removed, B default 20°, `from __future__`;
every sample is checked by tests through the full pipeline).

    python -m robocode.tools.sample_nc out_dir     # writes every sample as out_dir/<name>.nc
"""
from __future__ import annotations

import math
import sys
from pathlib import Path
from typing import Callable


def fmt(val: float) -> str:
    """Format a float with up to 4 decimals, no trailing zeros, no -0."""
    if abs(val) < 1e-6:
        val = 0.0
    s = f"{val:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _positive(**kw: float) -> None:
    bad = [k for k, v in kw.items() if not (isinstance(v, (int, float)) and math.isfinite(v) and v > 0)]
    if bad:
        raise ValueError(f"Arguments must be positive finite numbers: {', '.join(bad)}")


def _header(comment: str, inch: bool = False, safe_z: float = 10.0) -> list[str]:
    """Standard program header."""
    if "(" in comment or ")" in comment:
        raise ValueError("G-code comments cannot be nested: no parentheses inside the comment text")
    return [f"({comment})", "G20 G90 G17" if inch else "G21 G90 G17", "T1 M6", "S12000 M3", f"G0 Z{fmt(safe_z)}"]


def _footer(safe_z: float = 10.0) -> list[str]:
    """Standard program footer."""
    return [f"G0 Z{fmt(safe_z)}", "M5", "M30"]


def _join(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def square_pocket(size: float = 40.0, depth: float = 2.0, step_down: float = 1.0, feed: float = 600.0,
                  safe_z: float = 10.0) -> str:
    """Square contour passes at successive depths."""
    _positive(size=size, depth=depth, step_down=step_down, feed=feed, safe_z=safe_z)
    lines = _header("Square pocket contour passes", safe_z=safe_z)
    half = size / 2.0
    z = 0.0
    while z < depth - 1e-9:
        z = min(depth, z + step_down)
        lines += [f"G0 X{fmt(-half)} Y{fmt(-half)}", f"G1 Z{fmt(-z)} F{fmt(feed)}",
                  f"G1 X{fmt(half)}", f"G1 Y{fmt(half)}", f"G1 X{fmt(-half)}", f"G1 Y{fmt(-half)}",
                  f"G0 Z{fmt(safe_z)}"]
    lines += _footer(safe_z)
    return _join(lines)


def circle(radius: float = 20.0, depth: float = 1.0, feed: float = 500.0, safe_z: float = 10.0,
           cw: bool = True) -> str:
    """Full circle as one G2/G3 with I/J, starting at (radius, 0)."""
    _positive(radius=radius, depth=depth, feed=feed, safe_z=safe_z)
    lines = _header(f"Full circle {'CW' if cw else 'CCW'}", safe_z=safe_z)
    lines += [f"G0 X{fmt(radius)} Y0", f"G1 Z{fmt(-depth)} F{fmt(feed)}",
              f"{'G2' if cw else 'G3'} X{fmt(radius)} Y0 I{fmt(-radius)} J0"]
    lines += _footer(safe_z)
    return _join(lines)


def helix(radius: float = 10.0, depth: float = 3.0, turns: float = 3.0, feed: float = 300.0,
          safe_z: float = 5.0) -> str:
    """Helical ramp: `turns` full circles (G3), each lowering Z by depth/turns."""
    _positive(radius=radius, depth=depth, turns=turns, feed=feed, safe_z=safe_z)
    lines = _header("Helical ramp", safe_z=safe_z)
    lines += [f"G0 X{fmt(radius)} Y0", "G0 Z1", f"G1 Z0 F{fmt(feed)}"]
    for i in range(1, int(math.ceil(turns)) + 1):
        z = -depth / turns * min(float(i), turns)
        lines.append(f"G3 X{fmt(radius)} Y0 Z{fmt(z)} I{fmt(-radius)} J0")
    lines += _footer(safe_z)
    return _join(lines)


def r_arcs(radius: float = 15.0, feed: float = 400.0, safe_z: float = 10.0) -> str:
    """Four quarter arcs with R: short CW, short CCW (R>0), long CW, long CCW (R<0)."""
    _positive(radius=radius, feed=feed, safe_z=safe_z)
    r = radius
    lines = _header("R-word arcs, short and long", safe_z=safe_z)
    lines += ["G0 X0 Y0", f"G1 Z-1 F{fmt(feed)}",
              f"G2 X{fmt(r)} Y{fmt(r)} R{fmt(r)}",          # short CW
              f"G3 X{fmt(2 * r)} Y0 R{fmt(r)}",             # short CCW
              f"G2 X{fmt(r)} Y{fmt(-r)} R{fmt(-r)}",        # long CW
              f"G3 X0 Y0 R{fmt(-r)}"]                       # long CCW
    lines += _footer(safe_z)
    return _join(lines)


def zx_arc(radius: float = 10.0, feed: float = 400.0, safe_z: float = 10.0) -> str:
    """One G18 semicircle in the ZX plane using I and K."""
    _positive(radius=radius, feed=feed, safe_z=safe_z)
    lines = _header("ZX plane arc G18", safe_z=safe_z)
    lines += ["G0 X0 Y0 Z1", f"G1 Z0 F{fmt(feed)}", "G18",
              f"G2 X{fmt(2 * radius)} Z0 I{fmt(radius)} K0", "G17"]
    lines += _footer(safe_z)
    return _join(lines)


def tilted_lines(length: float = 50.0, b_angle: float = 20.0, feed: float = 500.0, safe_z: float = 20.0) -> str:
    """G1 moves with B head angles 0, +b_angle, -b_angle."""
    _positive(length=length, b_angle=b_angle, feed=feed, safe_z=safe_z)
    lines = _header("Tilted lines with B axis", safe_z=safe_z)
    lines += ["G0 X0 Y0", f"G1 Z-1 F{fmt(feed)}", f"G1 X{fmt(length)} B0",
              f"G1 X0 B{fmt(b_angle)}", f"G1 X{fmt(length)} B{fmt(-b_angle)}", "G1 B0"]
    lines += _footer(safe_z)
    return _join(lines)


def inch_square(size_in: float = 1.0, depth_in: float = 0.05, feed_ipm: float = 20.0) -> str:
    """Single-pass square in inches (G20)."""
    _positive(size_in=size_in, depth_in=depth_in, feed_ipm=feed_ipm)
    safe = 0.5
    half = size_in / 2.0
    lines = _header("Inch square", inch=True, safe_z=safe)
    lines += [f"G0 X{fmt(-half)} Y{fmt(-half)}", f"G1 Z{fmt(-depth_in)} F{fmt(feed_ipm)}",
              f"G1 X{fmt(half)}", f"G1 Y{fmt(half)}", f"G1 X{fmt(-half)}", f"G1 Y{fmt(-half)}"]
    lines += _footer(safe)
    return _join(lines)


ALL_SAMPLES: dict[str, Callable[[], str]] = {
    "square_pocket": square_pocket, "circle": circle, "helix": helix, "r_arcs": r_arcs,
    "zx_arc": zx_arc, "tilted_lines": tilted_lines, "inch_square": inch_square,
}


def write_samples(out_dir: str | Path) -> list[Path]:
    """Write every sample to out_dir/<name>.nc and return the paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, gen in ALL_SAMPLES.items():
        p = out / f"{name}.nc"
        p.write_text(gen(), encoding="utf-8", newline="\n")
        paths.append(p)
    return paths


def main(argv: list[str] | None = None) -> int:
    """CLI: python -m robocode.tools.sample_nc out_dir"""
    argv = sys.argv[1:] if argv is None else argv
    if not argv:
        print("Użycie: python -m robocode.tools.sample_nc FOLDER", file=sys.stderr)
        return 1
    for p in write_samples(argv[0]):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
